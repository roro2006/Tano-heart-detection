"""Generate the softmax exp ROM and deterministic attention vectors.

Usage: python3 python/generate_artifacts.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from q8_attention import EXP_LUT, attention_q8_8, q8_8

ROOT = Path(__file__).resolve().parents[1]


def write_mem(path: Path, values: list[int], digits: int = 4) -> None:
    mask = (1 << (4 * digits)) - 1
    path.write_text("".join(f"{value & mask:0{digits}x}\n" for value in values))


def exp_rom_sv() -> str:
    lines = [
        "// Generated by python/generate_artifacts.py from q8_attention.EXP_LUT. Do not edit.",
        "// Q0.16 exp(-n/16) for n in [0, 255]; entry 0 is exactly 65536.",
        "module exp_rom (",
        "    input  logic [7:0] index,",
        "    output logic [16:0] value",
        ");",
        "    always_comb begin",
        "        case (index)",
    ]
    lines += [f"            8'd{n}: value = 17'd{v};" for n, v in enumerate(EXP_LUT)]
    lines += ["            default: value = 17'd0;", "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def main() -> None:
    (ROOT / "weights").mkdir(exist_ok=True)
    # EXP_LUT[0] is 65536, so the ROM needs 17 bits (five hex digits).
    write_mem(ROOT / "weights" / "softmax_exp.mem", list(EXP_LUT), digits=5)
    (ROOT / "rtl" / "exp_rom.sv").write_text(exp_rom_sv(), newline="\n")
    eye = [[256 if row == col else 0 for col in range(64)] for row in range(64)]
    x = [[q8_8(((row + col) % 9 - 4) / 8) for col in range(64)] for row in range(16)]
    output = attention_q8_8(x, eye, eye, eye)
    (ROOT / "sim").mkdir(exist_ok=True)
    (ROOT / "sim" / "attention_vector.json").write_text(json.dumps({"x": x, "expected": output}))
    print("generated rtl/exp_rom.sv, weights/softmax_exp.mem and sim/attention_vector.json")


if __name__ == "__main__":
    main()
